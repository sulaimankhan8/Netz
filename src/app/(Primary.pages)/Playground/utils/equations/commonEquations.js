/** The topic groups of a subject, in order (empty when its list is not grouped, as Math). */
export function groupsOf(subject) {
  const groups = [];
  for (const item of (subject && subject.items) || []) {
    if (item.group && !groups.includes(item.group)) groups.push(item.group);
  }
  return groups;
}

/** Chemistry needs mhchem; the visual editor cannot edit \ce{...}, so those open as LaTeX. */
export function usesChemistry(latex) {
  return /\\ce\{/.test(String(latex || ''));
}
