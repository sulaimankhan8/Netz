#!/usr/bin/env node
/**
 * Builds src/app/data/methodWidgets.js: for every method page built on SymbolicCalculator, the inputs its
 * Notes widget needs (start values and fields, copied as written on the page, `show` conditions included)
 * and a lazy import of its engine. Run after adding or changing a SymbolicCalculator page:
 *   npm run build:widgets
 * The Notes registry (Notes/utils/algorithmRegistry.js) turns these into widgets for the methods that are live.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')), '..');
const PAGES = path.join(ROOT, 'src/app/(pages.algorithems)');
const OUT = path.join(ROOT, 'src/app/data/methodWidgets.js');

/** The balanced {…} or […] starting at text[i] (skipping strings and template literals). */
function balanced(text, i) {
  const open = text[i], close = open === '{' ? '}' : ']';
  let depth = 0;
  for (let k = i; k < text.length; k++) {
    const ch = text[k];
    if (ch === '"' || ch === "'" || ch === '`') {
      const q = ch;
      for (k++; k < text.length && text[k] !== q; k++) if (text[k] === '\\') k++;
      continue;
    }
    if (ch === open) depth++;
    else if (ch === close && --depth === 0) return text.slice(i, k + 1);
  }
  return null;
}
/** The value of a JSX prop like start={…}: an inline literal, or a const it names. */
function prop(src, name) {
  const at = src.indexOf(`${name}={`);
  if (at < 0) return null;
  const j = at + name.length + 2;
  if (src[j] === '{' || src[j] === '[') return balanced(src, j);
  const ident = src.slice(j).match(/^([A-Za-z_]\w*)\}/);
  if (!ident) return null;
  const def = src.match(new RegExp(`const ${ident[1]} = ([\\[{])`));
  return def ? balanced(src, def.index + def[0].length - 1) : null;
}

const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/^algorithems\..*\.js$/.test(f.name)) files.push(p); } };
walk(PAGES);

const entries = [];
for (const f of files.sort()) {
  const src = fs.readFileSync(f, 'utf8');
  if (!src.includes('<SymbolicCalculator')) continue;
  const id = src.match(/<SymbolicCalculator[\s\S]*?\bid="([^"]+)"/)?.[1];
  const engine = src.match(/import \{ solve[^}]*\} from '@\/app\/utils\/engines\/([^']+)'/)?.[1];
  const start = prop(src, 'start'), fields = prop(src, 'fields');
  if (!id || !engine || !start || !fields) { console.warn(`skipped ${path.relative(ROOT, f)} (could not read id, engine, start or fields)`); continue; }
  // constants the fields or start values use (const MODES = [...] on the page), copied into the entry's own scope
  const consts = [];
  const seen = new Set();
  // names used outside strings (not after a dot, not an object key)
  // (a spread ...name still names name)
  const noStrings = (t) => t.replace(/(["'`])(?:\\.|(?!\1)[^\\])*\1/g, '""').replace(/\.\.\./g, ' ');
  const need = (text) => [...noStrings(text).matchAll(/(?<![.\w$])([A-Za-z_$][\w$]*)(?!\s*:)/g)].map((m) => m[1]).filter((n) => !seen.has(n));
  // names the page imports (other than the engine's solve) cannot be copied
  const imported = new Set([...src.matchAll(/^import \{([^}]*)\}/gm)].flatMap((m) => m[1].split(',').map((s) => s.trim().split(/\s+as\s+/).pop())).filter((n) => n && n !== 'solve'));
  let queue = need(start + fields);
  let missing = null;
  while (queue.length) {
    const n = queue.shift();
    if (seen.has(n)) continue;
    seen.add(n);
    if (imported.has(n)) { missing = n; continue; }
    const def = src.match(new RegExp(`^(?:export )?const ${n.replace(/\$/g, '\\$')} = `, 'm'));
    if (!def) continue;
    let k = def.index + def[0].length;
    let value;
    if (src[k] === '[' || src[k] === '{') value = balanced(src, k);
    else { const end = src.indexOf(';\n', k); value = src.slice(k, end); }
    consts.unshift(`const ${n} = ${value};`);
    queue.push(...need(value));
  }
  if (missing) { console.warn(`skipped ${path.relative(ROOT, f)} (its fields use ${missing}, imported from elsewhere)`); continue; }
  const body = `{\n    id: ${JSON.stringify(id)},\n    load: () => import('@/app/utils/engines/${engine}'),\n    start: ${start},\n    fields: ${fields},\n  }`;
  entries.push(consts.length ? `  (() => {\n    ${consts.join('\n    ')}\n    return ${body};\n  })(),` : `  ${body},`);
}

fs.writeFileSync(OUT, `// Generated by scripts/build-widget-data.mjs (npm run build:widgets). Do not edit by hand.
// Inputs for the Notes widget of every SymbolicCalculator page, copied from the page, and its engine (loaded on demand).
/* eslint-disable */
export const METHOD_WIDGETS = [
${entries.join('\n')}
];
`);
console.log(`wrote ${entries.length} widgets to ${path.relative(ROOT, OUT)}`);

// A small list of which pages have a Notes widget, for the "Open in Notes" link on method pages (the full file above
// is too big to load on every page)
const ids = entries.map((e) => e.match(/id: ("[^"]+")/)[1]);
const IDS_OUT = path.join(ROOT, 'src/app/data/methodWidgetIds.js');
fs.writeFileSync(IDS_OUT, `// Generated by scripts/build-widget-data.mjs (npm run build:widgets). Do not edit by hand.
// Method pages whose calculator can be added to a note as a live widget (besides the 34 original pages).
export const NOTES_WIDGET_IDS = new Set([
${ids.map((i) => `  ${i},`).join('\n')}
]);
`);
console.log(`wrote ${ids.length} ids to ${path.relative(ROOT, IDS_OUT)}`);
